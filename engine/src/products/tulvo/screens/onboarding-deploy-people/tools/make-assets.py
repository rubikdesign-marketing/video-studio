#!/usr/bin/env python3
"""
Regenerates ../assets.ts (data URIs) from the live screenshots in research/ui-live/day2:
  - onboarding-panel-bg : the blurred onboarding panel image as displayed (day2/12, box 764,8 704x789 CSS px)
  - integration-banner  : the Slack/Notion connect banner image (padding box 553,137 654x158), day2/04 + 05 averaged,
                          centred tile row inpainted by vertical interpolation (the rebuilt tiles are drawn on top).
Both are Tulvo's own artwork. The app serves them as /assets/onboarding-panel-bg-*.jpg and /assets/banner-bg-*.png,
which were not captured; these crops reproduce what the app displays at 1512x805.
usage (from engine/): python3 -I src/products/tulvo/screens/onboarding-deploy-people/tools/make-assets.py
"""
import subprocess, sys


def load(path, scale=None):
    vf = "format=rgb24" if not scale else f"scale={scale}:flags=lanczos,format=rgb24"
    out = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-vf", vf, "-frames:v", "1", "-f", "image2pipe", "-vcodec", "ppm", "pipe:1"],
                         capture_output=True, check=True).stdout
    # parse P6 header
    parts = []
    i = 0
    while len(parts) < 4:
        while out[i:i + 1].isspace():
            i += 1
        j = i
        while not out[j:j + 1].isspace():
            j += 1
        parts.append(out[i:j])
        i = j
    i += 1
    w, h = int(parts[1]), int(parts[2])
    return w, h, out[i:]


class Img:
    def __init__(self, path, scale=None):
        self.w, self.h, self.d = load(path, scale)

    def px(self, x, y):
        o = (y * self.w + x) * 3
        return tuple(self.d[o:o + 3])




import base64, os, tempfile

DAY2 = "research/ui-live/day2"
OUT_TS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets.ts")


def crop(im, x0, y0, w, h):
    out = bytearray()
    for y in range(y0, y0 + h):
        o = (y * im.w + x0) * 3
        out += im.d[o:o + w * 3]
    return out


def to_jpeg_data_uri(w, h, data):
    with tempfile.TemporaryDirectory() as td:
        ppm, jpg = os.path.join(td, "a.ppm"), os.path.join(td, "a.jpg")
        with open(ppm, "wb") as f:
            f.write(f"P6\n{w} {h}\n255\n".encode())
            f.write(bytes(data))
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", ppm, "-q:v", "2", jpg], check=True)
        return "data:image/jpeg;base64," + base64.b64encode(open(jpg, "rb").read()).decode()


def onboarding_panel():
    im = Img(f"{DAY2}/12-onboarding-use-tulvo-ai.jpg")
    return to_jpeg_data_uri(704, 789, crop(im, 764, 8, 704, 789))


def integration_banner():
    a = Img(f"{DAY2}/04-integrations-slack-connect.jpg")
    b = Img(f"{DAY2}/05-integrations-notion-connect.jpg")
    X0, Y0, W, H = 553, 137, 654, 158
    avg = bytearray((p + q + 1) // 2 for p, q in zip(crop(a, X0, Y0, W, H), crop(b, X0, Y0, W, H)))
    ix0, ix1, iy0, iy1 = 758 - X0, 1002 - X0, 182 - Y0, 250 - Y0

    def px(x, y):
        o = (y * W + x) * 3
        return avg[o:o + 3]

    def vavg(x, y, r=2):
        rows = [px(x, yy) for yy in range(y - r, y + r + 1)]
        return [sum(p[k] for p in rows) / len(rows) for k in range(3)]

    for x in range(ix0, ix1):
        top, bot = vavg(x, iy0 - 3), vavg(x, iy1 + 3)
        for y in range(iy0, iy1):
            t = (y - iy0) / (iy1 - iy0)
            o = (y * W + x) * 3
            for k in range(3):
                avg[o + k] = int(round(top[k] * (1 - t) + bot[k] * t))
    for y in range(iy0, iy1):
        for xs in (range(ix0 - 6, ix0 + 6), range(ix1 - 6, ix1 + 6)):
            row = [list(px(x, y)) for x in range(xs.start - 2, xs.stop + 2)]
            for i, x in enumerate(xs):
                o = (y * W + x) * 3
                for k in range(3):
                    avg[o + k] = int(round(sum(row[i + j][k] for j in range(5)) / 5))
    return to_jpeg_data_uri(W, H, avg)


if __name__ == "__main__":
    ts = (
        "/**\n * GENERATED by tools/make-assets.py from the live screenshots (research/ui-live/day2). Do not edit.\n"
        " * Tulvo's own artwork as the app displays it at 1512x805 (see the script for the crop boxes).\n */\n"
        f'export const ONBOARDING_PANEL_BG = "{onboarding_panel()}";\n'
        f'export const INTEGRATION_BANNER_BG = "{integration_banner()}";\n'
    )
    with open(OUT_TS, "w") as f:
        f.write(ts)
    print(OUT_TS, len(ts))
