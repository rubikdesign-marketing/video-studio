"""Write ../textWidth.ts from the decoded measurement (see measure-inter.tsx).

    npx remotion still src/products/tulvo/screens/home/tools/measure-inter.tsx MeasureInter m.png
    python3 -I src/products/tulvo/screens/home/tools/decode-widths.py m.png > widths.json
    python3 -I src/products/tulvo/screens/home/tools/gen-text-widths.py widths.json
"""
import json
import os
import sys

d = json.load(open(sys.argv[1]))
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "textWidth.ts")


def table(w):
    chars = d[w]["chars"]
    return "".join(f"{json.dumps(k)}: {round(v, 3)}, " for k, v in chars.items())


def samples(w):
    return "".join(f"{json.dumps(k)}: {round(v, 3)}, " for k, v in d[w]["samples"].items())


src = f'''/**
 * GENERATED by tools/gen-text-widths.py from tools/measure-inter.tsx (Inter as loaded by fonts.ts,
 * measured in Remotion's Chrome). Do not edit by hand.
 *
 * Why: recharts decides which x-axis tick labels to show (and shifts the first/last one inside the
 * chart) from measured label widths. The live app measured them at Inter 10px weight 600 (recharts'
 * shared measurement <span> keeps the label list's font-weight: 600), with bounds [0, chart width]:
 * that reproduces every captured tick x exactly (Prospecting 29.148, Oct 2026 22.516, Nov 2026 300.328).
 * Components must be pure (no DOM measuring during render), so the widths are a static table.
 */

/** Advance width (px) of each printable ASCII char at 10px, by font weight. Kerning not included. */
const CHAR_10PX: Record<400 | 600, Record<string, number>> = {{
  400: {{ {table("400")}}},
  600: {{ {table("600")}}},
}};

/** Exact whole-string widths (px, 10px) for the labels the Home charts show by default. */
const EXACT_10PX: Record<400 | 600, Record<string, number>> = {{
  400: {{ {samples("400")}}},
  600: {{ {samples("600")}}},
}};

/** Width in px of `text` in Inter at `fontSize` (exact for known labels, else per-char sum within ~1px). */
export const interTextWidth = (text: string, fontSize = 10, weight: 400 | 600 = 600): number => {{
  const exact = EXACT_10PX[weight][text];
  const base =
    exact ?? [...text].reduce((sum, ch) => sum + (CHAR_10PX[weight][ch] ?? CHAR_10PX[weight]["n"]), 0);
  return (base * fontSize) / 10;
}};

/** recharts' tick-size function as the live app ran it: Inter 10px, weight 600. */
export const rechartsTickWidth = (text: string): number => interTextWidth(text, 10, 600);
'''
open(out, "w").write(src)
print("wrote", out)
